// Writes the committed framework-token snapshot (src/frameworkTokens.snapshot.json) from the webapp's
// stylesheets. The snapshot itself and the reason it exists live next to the data, in src/frameworkTokens.ts;
// only the GENERATOR is here, so that reading the tokens at runtime never pulls postcss into a server
// process (see lib/css.ts).
//
// Run it with `npm run tokens:snapshot`. framework-tokens.spec.ts fails when the snapshot drifts from
// the stylesheets, in the checkouts where those can be read.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { computeCatalog } from './theme-catalog.ts'

const SNAPSHOT = new URL('../src/frameworkTokens.generated.ts', import.meta.url)

const HEADER = `// GENERATED by \`npm run tokens:snapshot\` — do not edit.
//
// A TypeScript module rather than the JSON it looks like, because src/ is type-checked as ESM
// (module: nodenext, which demands an \`with { type: 'json' }\` import attribute) and COMPILED as
// CommonJS (module: commonjs, where that attribute is an error). No single JSON import satisfies both;
// a plain data module satisfies neither constraint by having none.
//
// Why the values live here at all: see src/frameworkTokens.ts.
`

/** Prettier's own quoting rules, so the generated file needs no reformatting to pass lint. */
function quote(value: string): string {
  return value.includes("'") && !value.includes('"')
    ? JSON.stringify(value)
    : `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

/** The module source for a token map — exported so the drift guard can compare without writing. */
export function renderFrameworkTokens(tokens: Record<string, string>): string {
  // Sorted, so a regenerated file diffs by VALUE and not by whatever order readdir returned.
  const entries = Object.entries(tokens)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, value]) => {
      // Prettier breaks after the colon when the entry would exceed printWidth (100) — matching it
      // here is what keeps the generated file lint-clean without an eslint-disable header.
      const line = `  ${quote(name)}: ${quote(value)},`
      return line.length <= 100 ? line : `  ${quote(name)}:\n    ${quote(value)},`
    })
  return `${HEADER}
export const FRAMEWORK_TOKENS: Record<string, string> = {
${entries.join('\n')}
}
`
}

const PUBLIC_TOKENS = new URL('./public-tokens.snapshot.json', import.meta.url)

/**
 * The names a brand may have set, as the list in public-tokens.snapshot.json plus `current`. Only ever
 * ADDS: a name that is gone from the stylesheets stays, so scripts/public-tokens.spec.ts can fail on it
 * — dropping it here would hide exactly what that test exists to catch.
 */
export function mergePublicTokens(known: readonly string[], current: Iterable<string>): string[] {
  return [...new Set([...known, ...current])].sort((a, b) => (a < b ? -1 : 1))
}

/** Whether a value reads `var(--name` as a reference of its own: `var(--name)` or `var(--name, …)`. */
function redirectsTo(value: string, name: string): boolean {
  const squeezed = value.replace(/\s+/g, '')
  return squeezed.includes(`var(--${name},`) || squeezed.includes(`var(--${name})`)
}

/**
 * What is wrong with the removedTokens list, as sentences. A token listed there is really gone and was
 * public; one with a `use` has a successor that falls back to it — without that fallback the rename
 * would be a plain removal, and a brand's value for the old name would reach nobody.
 */
export function removedTokenProblems(
  removed: Readonly<Record<string, { use?: string; note?: string }>>,
  framework: Readonly<Record<string, string>>,
  listed: readonly string[],
): string[] {
  const problems: string[] = []
  for (const [name, { use, note }] of Object.entries(removed)) {
    if (Object.hasOwn(framework, name)) {
      problems.push(`--${name} is declared again: drop it from removedTokens`)
    }
    if (!listed.includes(name)) {
      problems.push(`--${name} was never a public token: drop it from removedTokens`)
    }
    if (!use && !note) {
      problems.push(`--${name} says neither what replaced it (use) nor what to do (note)`)
    }
    if (use) {
      const value = Object.hasOwn(framework, use) ? framework[use] : undefined
      if (value === undefined) {
        problems.push(`--${name}: its successor --${use} is not a framework token`)
      } else if (!redirectsTo(value, name)) {
        problems.push(
          `--${name}: its successor --${use} must fall back to it, as \`--${use}: var(--${name}, <default>)\` — ` +
            'otherwise a brand that still sets the old name reaches nobody',
        )
      }
    }
  }
  return problems
}

/** Rewrite the generated module from the webapp's stylesheets. Only meaningful in this repository. */
export function writeFrameworkTokens(outPath?: string, publicPath?: string): string {
  const out = outPath ?? fileURLToPath(SNAPSHOT)
  const catalog = computeCatalog()
  writeFileSync(out, renderFrameworkTokens(catalog))
  const list = publicPath ?? fileURLToPath(PUBLIC_TOKENS)
  const known = (JSON.parse(readFileSync(list, 'utf8')) as { tokens: string[] }).tokens
  writeFileSync(
    list,
    `${JSON.stringify({ tokens: mergePublicTokens(known, Object.keys(catalog)) }, null, 2)}\n`,
  )
  return out
}
