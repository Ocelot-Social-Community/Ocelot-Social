#!/usr/bin/env node
// Brand the standalone maintenance page from a brand's typed config.
//
//   node scripts/build-maintenance-branding.mjs <brand-dir> <maintenance-dir>
//
// The maintenance page is a SEPARATE static Nuxt app served (by nginx) when the main app is down —
// so it cannot use the runtime branding injection (the webapp that serves /branding/* is offline).
// It is therefore branded at BUILD time: this overlays the brand's theme + logo onto the maintenance
// app before it is built, the same way the webapp overlay works.
//
// It reuses the brand's runtime theme (branding.theme.cssVars → the maintenance already styles with
// var(--color-primary) etc.) and its squared logo, so a brand defines colours + logo ONCE and both
// the live app and the maintenance page follow. Idempotent (re-runnable): the brand block in
// branding.css is delimited and regenerated.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'

import { loadConfig } from './lib/load-config.mjs'

const [brandArg, maintenanceArg] = process.argv.slice(2)
if (!brandArg || !maintenanceArg) {
  console.error('usage: build-maintenance-branding.mjs <brand-dir> <maintenance-dir>')
  process.exit(1)
}
const brandDir = resolve(brandArg)
const maintenanceDir = resolve(maintenanceArg)

function findBrandConfig(dir) {
  for (const name of ['brand.config.ts', 'brand.config.mjs', 'brand.config.js']) {
    const p = join(dir, name)
    if (existsSync(p)) return p
  }
  throw new Error(`no brand.config.(ts|mjs|js) in ${dir}`)
}

const config = await loadConfig(findBrandConfig(brandDir))
const theme = config.theme ?? { cssVars: {}, fontFaces: [] }

// --- 1. Colours: append the brand's :root overrides to the maintenance branding.css --------------
const cssPath = join(maintenanceDir, 'app/assets/css/branding.css')
if (!existsSync(cssPath)) throw new Error(`maintenance branding.css not found: ${cssPath}`)
const MARK = '/* === brand overrides (generated by build-maintenance-branding.mjs) === */'
let css = readFileSync(cssPath, 'utf8')
const at = css.indexOf(MARK)
if (at !== -1) css = css.slice(0, at).trimEnd() + '\n' // strip a previous generated block

// Colours only (the maintenance page styles with var(--color-*)); fonts stay the maintenance
// default (its body uses LatoWeb literally) — a brand font would need the file copied + the body
// switched to var(--font-family-text), a separate follow-up.
const cssVars = theme.cssVars ?? {}
if (Object.keys(cssVars).length) {
  const vars = Object.entries(cssVars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')
  css += `\n${MARK}\n:root {\n${vars}\n}\n`
  writeFileSync(cssPath, css)
  // eslint-disable-next-line no-console
  console.log(`[maintenance] colours → ${cssPath} (${Object.keys(cssVars).length} vars)`)
}

// --- 2. Logo: copy the brand's squared logo to the maintenance public path -----------------------
const logoRel = config.logos?.signupPath || config.logos?.passwordResetPath // squared logo
if (logoRel && !/^(https?:|\/)/.test(logoRel)) {
  const src = join(brandDir, logoRel)
  const dest = join(maintenanceDir, 'public/img/custom', basename(logoRel))
  if (existsSync(src)) {
    copyFileSync(src, dest)
    // The maintenance app references /img/custom/logo-squared.svg — keep that stable name too.
    const stable = join(maintenanceDir, 'public/img/custom/logo-squared.svg')
    if (dest !== stable && /\.svg$/.test(src)) copyFileSync(src, stable)
    // eslint-disable-next-line no-console
    console.log(`[maintenance] logo → ${dest}`)
  } else {
    console.warn(`[maintenance] ! logo not found: ${src}`)
  }
}

// --- 3. Metadata: theme-color + app identity for the <head> --------------------------------------
const m = config.metadata ?? {}
const themeColor = cssVars['color-primary'] || m.themeColor || 'rgb(23, 181, 63)'
const metaPath = join(maintenanceDir, 'app/constants/metadata.ts')
if (existsSync(metaPath)) {
  const meta = {
    APPLICATION_NAME: m.applicationName ?? 'ocelot.social',
    APPLICATION_SHORT_NAME: m.applicationShortName ?? 'ocelot.social',
    APPLICATION_DESCRIPTION: m.applicationDescription ?? 'ocelot.social Community Network',
    ORGANIZATION_NAME: m.organizationName ?? 'ocelot.social Community',
    ORGANIZATION_JURISDICTION: m.organizationJurisdiction ?? 'City of Angels',
    THEME_COLOR: themeColor,
    OG_IMAGE: m.ogImage ?? '/img/custom/logo-squared.png',
    OG_IMAGE_ALT: m.ogImageAlt ?? 'ocelot.social Logo',
    OG_IMAGE_WIDTH: m.ogImageWidth ?? '1200',
    OG_IMAGE_HEIGHT: m.ogImageHeight ?? '1140',
    OG_IMAGE_TYPE: m.ogImageType ?? 'image/png',
  }
  const body = Object.entries(meta)
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
    .join('\n')
  writeFileSync(metaPath, `// Generated by build-maintenance-branding.mjs from the brand config.\nexport default {\n${body}\n};\n`)
  // eslint-disable-next-line no-console
  console.log(`[maintenance] metadata → ${metaPath} (theme-color ${themeColor})`)
}
